# Make each repo's maintainers the code owners of .github/ and of the CODEOWNERS file itself, so that
# with the org rules (apply-org-rules.sh) a Write user's change there needs a maintainer's approval.
# Maintainers = visible teams and direct collaborators with the admin or maintain role, or a --role;
# a repo without any gets the --fallback owners.
# The owners go in a marked block at the end of the repo's CODEOWNERS (the last matching line wins);
# a re-run replaces only that block. The block is committed to the default branch; where rules
# block that, a PR is opened instead (merging it is left to a person). Archived repos and forks are skipped.
# Needs admin on each repo.
#
#   scripts/apply-codeowners.sh [--dry-run] --fallback '@a @b' [--role <name>]... [--exclude-user <login>]... (--all <org> | owner/repo...)
#
# --role: a custom repository role that counts as maintainer (e.g. GateKeeper); repeatable.
# --exclude-user: a machine user that must not be a code owner (it could approve alone); repeatable.
set -euo pipefail

dry=false
fallback=""
roles=(admin maintain)
excluded=()
all_org=""
while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run) dry=true; shift ;;
    --fallback) fallback="${2:?--fallback needs owners}"; shift 2 ;;
    --role) roles+=("${2:?--role needs a role name}"); shift 2 ;;
    --exclude-user) excluded+=("${2:?--exclude-user needs a login}"); shift 2 ;;
    --all) all_org="${2:?--all needs an org}"; shift 2 ;;
    --*) echo "unknown option: $1" >&2; exit 2 ;;
    *) break ;;
  esac
done
usage="usage: $0 [--dry-run] --fallback '@a @b' [--role <name>]... [--exclude-user <login>]... (--all <org> | owner/repo...)"
[ -n "$fallback" ] || { echo "$usage" >&2; exit 2; }
if [ -n "$all_org" ]; then
  [ $# -eq 0 ] || { echo "$usage" >&2; exit 2; }
  repos=()
  while IFS= read -r r; do repos+=("$r"); done < <(gh api "orgs/$all_org/repos?per_page=100" --paginate --jq '.[] | select(.archived or .fork | not) | .full_name' | sort)
else
  [ $# -gt 0 ] || { echo "$usage" >&2; exit 2; }
  repos=("$@")
fi
roles_json=$(printf '%s\n' "${roles[@]}" | jq -R . | jq -sc .)
excluded_json=$(printf '%s\n' ${excluded[@]+"${excluded[@]}"} | jq -R 'select(. != "")' | jq -sc .)

begin="# BEGIN org baseline: maintainers own .github/ and CODEOWNERS (ci-infrastructure scripts/apply-codeowners.sh)"
end="# END org baseline"
branch="org-baseline-codeowners"
IFS= read -r -d '' pr_body <<'EOF' || true
### Description

Makes the repository's maintainers the code owners of `.github/` and of `CODEOWNERS`, so that changes to workflows and to the code owners need a maintainer's approval. Generated by `scripts/apply-codeowners.sh` in ci-infrastructure; a re-run replaces only the marked block.

### Contributor Declaration

By opening this pull request, I affirm the following:

* All authors agree to the [Contributor License Agreement](https://github.com/ecmwf/codex/blob/main/Legal/Contributor-License-Agreement.md).
* The code follows the project's coding standards.
* I have performed self-review and added comments where needed.
* I have added or updated tests to verify that my changes are effective and functional.
* I have run all existing tests and confirmed they pass.
EOF

# The maintainers of $repo as @-handles, space-separated; empty if none.
maintainers() {
  local org=${repo%%/*} teams users
  teams=$(gh api "repos/$repo/teams?per_page=100" --paginate --jq '.[]' | jq -r --argjson r "$roles_json" \
    'select(.privacy == "closed" and (.permission | IN($r[]))) | .slug' | sed "s|^|@$org/|")
  users=$(gh api "repos/$repo/collaborators?affiliation=direct&per_page=100" --paginate --jq '.[]' | jq -r --argjson r "$roles_json" --argjson x "$excluded_json" \
    'select(.type == "User" and (.role_name | IN($r[])) and (.login | IN($x[]) | not)) | .login' | sed 's/^/@/')
  printf '%s\n' "$teams" "$users" | grep -v '^$' | sort -u | paste -sd' ' - || true
}

# The active CODEOWNERS (GitHub reads the first of these) as "path<TAB>sha"; empty if there is none.
active_codeowners() {
  local path sha
  for path in .github/CODEOWNERS CODEOWNERS docs/CODEOWNERS; do
    if sha=$(gh api "repos/$repo/contents/$path" --jq .sha 2>/dev/null); then
      printf '%s\t%s\n' "$path" "$sha"
      return
    fi
  done
}

# $1 with the block replaced, or appended after a blank line.
with_block() {
  local block
  block=$(printf '%s\n/.github/ %s\n/CODEOWNERS %s\n/docs/CODEOWNERS %s\n%s' "$begin" "$owners" "$owners" "$owners" "$end")
  if grep -qxF "$begin" <<< "$1"; then
    BLOCK=$block awk -v b="$begin" -v e="$end" '$0 == b {print ENVIRON["BLOCK"]; skip = 1; next} skip && $0 == e {skip = 0; next} !skip' <<< "$1"
  elif [ -n "$1" ]; then
    printf '%s\n\n%s\n' "$1" "$block"
  else
    printf '%s\n' "$block"
  fi
}

# PUT $path with $new on branch $1; prints nothing, fails if a rule rejects it.
put() {
  jq -n --arg m "CODEOWNERS: maintainers own .github/ and CODEOWNERS" --arg c "$new" --arg b "$1" --arg s "$sha" \
    '{message: $m, content: ($c + "\n" | @base64), branch: $b} + if $s == "" then {} else {sha: $s} end' |
    gh api -X PUT "repos/$repo/contents/$path" --input - >/dev/null
}

failed=false
printf 'repo\towners from\tfile\taction\towners\n'
for repo in "${repos[@]}"; do
  if ! default=$(gh api "repos/$repo" --jq .default_branch 2>/dev/null) ||
     ! gh api "repos/$repo/branches/$default" --silent 2>/dev/null; then
    printf '%s\t-\t-\tskipped (empty or unreadable)\t-\n' "$repo"
    continue
  fi
  owners=$(maintainers)
  source=maintainers
  [ -n "$owners" ] || { owners=$fallback; source=fallback; }

  path=.github/CODEOWNERS sha="" old=""
  if found=$(active_codeowners) && [ -n "$found" ]; then
    IFS=$'\t' read -r path sha <<< "$found"
    old=$(gh api -H "Accept: application/vnd.github.raw+json" "repos/$repo/contents/$path")
  fi
  new=$(with_block "$old")

  if [ "$new" == "$old" ]; then
    action=unchanged
  elif $dry; then
    action=$([ -n "$sha" ] && echo "would update" || echo "would create")
    diff -u --label "$repo/$path (current)" --label "$repo/$path (new)" <(printf '%s' "${old:+$old$'\n'}") <(printf '%s\n' "$new") | sed 's/^/    /' >&2 || true
  elif put "$default" 2>/dev/null; then
    action=$([ -n "$sha" ] && echo updated || echo created)
  else
    # A rule rejected the direct commit: the same change as a PR.
    head=$(gh api "repos/$repo/git/ref/heads/$default" --jq .object.sha)
    if gh api -X POST "repos/$repo/git/refs" -f ref="refs/heads/$branch" -f sha="$head" >/dev/null 2>&1 &&
       put "$branch" &&
       url=$(gh pr create -R "$repo" --base "$default" --head "$branch" \
         --title "CODEOWNERS: maintainers own .github/ and CODEOWNERS" --body "$pr_body"); then
      action="PR $url"
    else
      action="FAILED (branch $branch may exist already)"
      failed=true
    fi
  fi
  printf '%s\t%s\t%s\t%s\t%s\n' "$repo" "$source" "$path" "$action" "$owners"
done
$failed && exit 1
exit 0
