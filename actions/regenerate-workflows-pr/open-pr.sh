# Commit the regenerated workflows in the current checkout of $GH_REPO and push them to $BASE or open a PR.
# shellcheck disable=SC2016,SC2153  # backticks are Markdown; LABELS comes from the env
# Env: GH_TOKEN, GH_REPO, APP_SLUG, BRANCH, BASE, LABELS, TITLE, MODE, DIRECT_PUSH, RUN_URL; writes $GITHUB_OUTPUT.

set -euo pipefail
if [ "$DIRECT_PUSH" = true ]; then
  echo "::warning title=Regenerate workflows::direct-push is deprecated; use mode: auto-commit."
  [ "$MODE" = pr ] && MODE=auto-commit
fi
case "$MODE" in
  pr|pr-auto-merge|auto-commit) ;;
  *) echo "::error title=Regenerate workflows::mode must be pr, pr-auto-merge or auto-commit, not '$MODE'."; exit 1 ;;
esac
title="${TITLE:-Regenerate downstream-CI workflows}"
open_pr=$(gh pr list --head "$BRANCH" --base "$BASE" --state open --json url --jq '.[0].url // ""')

if [ -z "$(git status --porcelain -- .github/workflows)" ]; then
  if [ -n "$open_pr" ]; then
    gh pr close "$open_pr" --delete-branch --comment "The generated workflows on \`$BASE\` are up to date again ($RUN_URL)."
  fi
  echo "Generated workflows are up to date."
  echo "status=up-to-date" >> "$GITHUB_OUTPUT"
  exit 0
fi

bot="${APP_SLUG}[bot]"
bot_id=$(gh api "users/$bot" --jq .id)
git add -A -- .github/workflows
[ -f .pre-commit-config.yaml ] && git add -- .pre-commit-config.yaml
git -c user.name="$bot" -c user.email="${bot_id}+${bot}@users.noreply.github.com" commit -q -m "$title"

# Not forced: a concurrent push to base is rejected and the PR takes over.
if [ "$MODE" = auto-commit ]; then
  if git -c http.https://github.com/.extraheader= push -q \
      "https://x-access-token:${GH_TOKEN}@github.com/${GH_REPO}.git" "HEAD:refs/heads/$BASE"; then
    if [ -n "$open_pr" ]; then
      gh pr close "$open_pr" --delete-branch --comment "Pushed the regenerated workflows to \`$BASE\` directly ($RUN_URL)."
    fi
    echo "::notice title=Regenerate workflows::Pushed $(git rev-parse HEAD) to $BASE."
    echo "status=pushed" >> "$GITHUB_OUTPUT"
    exit 0
  fi
  echo "::warning title=Regenerate workflows::Could not push to $BASE; opening a PR instead."
fi

# Rewriting identical workflows would retrigger CI on the PR every night, as would a hook rev
# that moves with every push to ci-infrastructure.
remote_tree=$(gh api "repos/$GH_REPO/contents/.github?ref=$BRANCH" \
  --jq '.[] | select(.name == "workflows") | .sha' 2>/dev/null || true)
if [ -n "$open_pr" ] && [ "$remote_tree" = "$(git rev-parse 'HEAD:.github/workflows')" ]; then
  echo "::notice title=Regenerate workflows::$open_pr already has these changes."
  status=pr-unchanged
else
  # Empty extraheader drops any credentials actions/checkout persisted.
  git -c http.https://github.com/.extraheader= push -q --force \
    "https://x-access-token:${GH_TOKEN}@github.com/${GH_REPO}.git" "HEAD:refs/heads/$BRANCH"

  body=$(printf 'The generated downstream-CI workflows drifted from `.ci/manifest.toml`, the sibling manifests or the generator. Regenerated by %s.\n\n```\n%s\n```\n' \
    "$RUN_URL" "$(git diff --name-status HEAD~1)")
  if [ -n "$open_pr" ]; then
    # The title too, so a changed `title` input reaches a PR that is already open.
    gh pr edit "$open_pr" --title "$title" --body "$body"
    status=pr-updated
  else
    # gh pr create fails on a label the repo lacks; this runs org-wide, so leave such a label out.
    existing=$(gh label list --limit 1000 --json name --jq '.[].name')
    labels=()
    IFS=',' read -ra wanted <<< "$LABELS"
    for label in "${wanted[@]}"; do
      label="${label#"${label%%[![:space:]]*}"}"; label="${label%"${label##*[![:space:]]}"}"
      [ -n "$label" ] || continue
      if grep -qxF -- "$label" <<< "$existing"; then
        labels+=(--label "$label")
      else
        echo "::warning title=Regenerate workflows::$GH_REPO has no label '$label'; opening the PR without it."
      fi
    done
    open_pr=$(gh pr create --head "$BRANCH" --base "$BASE" --title "$title" --body "$body" "${labels[@]}")
    status=pr-opened
  fi
  echo "::notice title=Regenerate workflows::$open_pr"
fi

# Squash where allowed, else the method the repo does allow (eckit: merge commits only).
# Not fatal: the PR stays open for a human when the repo does not allow auto-merge.
if [ "$MODE" = pr-auto-merge ]; then
  errors=""
  for method in squash merge rebase; do
    if err=$(gh pr merge "$open_pr" --auto "--$method" 2>&1); then errors=""; break; fi
    errors+="$method: $err; "
  done
  if [ -n "$errors" ]; then
    echo "::warning title=Regenerate workflows::Could not enable auto-merge on $open_pr; is \"Allow auto-merge\" on? ${errors}"
  fi
fi
{ echo "status=$status"; echo "pr-url=$open_pr"; } >> "$GITHUB_OUTPUT"
